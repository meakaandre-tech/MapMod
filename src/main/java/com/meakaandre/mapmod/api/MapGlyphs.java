    /**
     * Adds a glyph: nine rows of nine characters, '#' for a set pixel and anything else for a clear one. Returns its
     * number, for {@link PoiKind.Builder#glyph}. Call it while the game starts, on both sides.
     */
    public static synchronized int register(String... rows) {
        if (rows.length != SIZE) throw new IllegalArgumentException("a glyph has " + SIZE + " rows, not " + rows.length);
        for (String row : rows) if (row.length() != SIZE) throw new IllegalArgumentException("a glyph row has " + SIZE + " characters: " + row);
        ALL.add(rows.clone());
        return ALL.size() - 1;
    }

    public static synchronized int count() {
        return ALL.size();
    }

    /** True if the glyph has a set pixel at x, y. */
    public static synchronized boolean set(int glyph, int x, int y) {
        if (glyph < 0 || glyph >= ALL.size() || x < 0 || y < 0 || x >= SIZE || y >= SIZE) return false;
        return ALL.get(glyph)[y].charAt(x) == '#';
    }
